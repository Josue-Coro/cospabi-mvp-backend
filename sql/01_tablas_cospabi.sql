-- =====================================================================
-- COSPABI R.L. - MVP de los 6 modulos (socio -> lectura -> aviso -> pago) + facturacion
-- Tablas traducidas del script de SQL Server (BD_COSPABI.sql) a PostgreSQL
-- 21 tablas (20 del sistema original + factura). Mismos nombres de tablas y columnas.
-- =====================================================================

-- ---------- ADMINISTRACION ----------
CREATE TABLE rol (
    id_rol       integer GENERATED BY DEFAULT AS IDENTITY,
    nombre       varchar(150) NOT NULL,
    descripcion  varchar(250),
    estado       boolean NOT NULL,
    CONSTRAINT rol_pk PRIMARY KEY (id_rol)
);

CREATE TABLE usuario_admin (
    id_usuario_admin    integer GENERATED BY DEFAULT AS IDENTITY,
    nombre              varchar(255) NOT NULL,
    apellido            varchar(255) NOT NULL,
    usuario             varchar(255) NOT NULL,
    contraseña          varchar(550) NOT NULL,
    estado              boolean NOT NULL,
    fecha_creacion      date NOT NULL,
    rol_id_rol          integer NOT NULL,
    intentos_fallidos   integer NOT NULL DEFAULT 0,
    bloqueado_hasta     timestamp,
    correo              varchar(150),
    debe_cambiar_clave  boolean NOT NULL DEFAULT false,
    CONSTRAINT usuario_admin_pk PRIMARY KEY (id_usuario_admin),
    CONSTRAINT usuario_admin_usuario_uq UNIQUE (usuario),
    CONSTRAINT usuario_admin_rol_fk FOREIGN KEY (rol_id_rol) REFERENCES rol (id_rol)
);

CREATE TABLE caja (
    id_caja                         integer GENERATED BY DEFAULT AS IDENTITY,
    fecha                           date NOT NULL,
    hora_apertura                   timestamp NOT NULL,
    hora_cierre                     timestamp,
    monto_cobrado                   numeric(30,2),
    usuario_admin_id_usuario_admin  integer NOT NULL,
    estado                          boolean NOT NULL,
    monto_apertura                  numeric(30,2) NOT NULL DEFAULT 0,
    monto_contado                   numeric(30,2),
    diferencia_arqueo               numeric(30,2),
    observacion_cierre              varchar(255),
    CONSTRAINT caja_pk PRIMARY KEY (id_caja),
    CONSTRAINT caja_usuario_admin_fk FOREIGN KEY (usuario_admin_id_usuario_admin)
        REFERENCES usuario_admin (id_usuario_admin),
    CONSTRAINT caja_contado_ck CHECK (monto_contado >= 0
        AND (diferencia_arqueo = 0 OR observacion_cierre IS NOT NULL)),
    CONSTRAINT caja_montos_ck CHECK (monto_apertura >= 0 AND monto_cobrado >= 0)
);

-- ---------- CONFIGURACION ----------
CREATE TABLE rol_socio (
    id_rol_socio  integer GENERATED BY DEFAULT AS IDENTITY,
    rol_socio     varchar(150) NOT NULL,
    CONSTRAINT rol_socio_pk PRIMARY KEY (id_rol_socio)
);

CREATE TABLE tarifa (
    id_tarifa               integer GENERATED BY DEFAULT AS IDENTITY,
    consumo_minimo_m3       integer,
    monto_minimo            numeric(30,2) NOT NULL,
    precio_m3               integer NOT NULL,
    rol_socio_id_rol_socio  integer NOT NULL,
    CONSTRAINT tarifa_pk PRIMARY KEY (id_tarifa),
    CONSTRAINT tarifa_rol_socio_fk FOREIGN KEY (rol_socio_id_rol_socio)
        REFERENCES rol_socio (id_rol_socio),
    CONSTRAINT tarifa_valores_ck CHECK (consumo_minimo_m3 >= 0
        AND monto_minimo >= 0 AND precio_m3 >= 0)
);

CREATE TABLE medidor (
    id_medidor         integer GENERATED BY DEFAULT AS IDENTITY,
    serie              varchar(150) NOT NULL,
    numero             integer NOT NULL,
    fecha_instalacion  date,
    CONSTRAINT medidor_pk PRIMARY KEY (id_medidor),
    CONSTRAINT medidor_serie_uq UNIQUE (serie),
    CONSTRAINT medidor_numero_ck CHECK (numero > 0)
);

CREATE TABLE periodo (
    id_periodo         integer GENERATED BY DEFAULT AS IDENTITY,
    periodo            varchar(50) NOT NULL,
    costo_inscripcion  numeric(10,2),
    CONSTRAINT periodo_pk PRIMARY KEY (id_periodo),
    CONSTRAINT periodo_periodo_uq UNIQUE (periodo)
);

-- ---------- ATENCION AL CLIENTE ----------
CREATE TABLE persona (
    id_persona        integer GENERATED BY DEFAULT AS IDENTITY,
    genero            varchar(255),
    nombre_completo   varchar(250) NOT NULL,
    ci                varchar(50) NOT NULL,
    fecha_nacimiento  date NOT NULL,
    fecha_registro    date NOT NULL,
    estado            boolean NOT NULL,
    telefono          integer,
    CONSTRAINT persona_pk PRIMARY KEY (id_persona),
    CONSTRAINT persona_ci_uq UNIQUE (ci),
    CONSTRAINT persona_ci_ck CHECK (ci ~ '^[0-9]{4,10}$'),
    CONSTRAINT persona_genero_ck CHECK (genero IN ('Masculino', 'Femenino', 'Otro')),
    CONSTRAINT persona_telefono_ck CHECK (telefono >= 10000000 AND telefono <= 99999999)
);

CREATE TABLE ruta (
    id_ruta      integer GENERATED BY DEFAULT AS IDENTITY,
    ruta         integer NOT NULL,
    descripcion  varchar(150),
    CONSTRAINT ruta_pk PRIMARY KEY (id_ruta),
    CONSTRAINT ruta_ruta_ck CHECK (ruta > 0)
);

CREATE TABLE socio (
    id_socio                integer GENERATED BY DEFAULT AS IDENTITY,
    nombre_socio            varchar(255) NOT NULL,
    persona_id_persona      integer NOT NULL,
    rol_socio_id_rol_socio  integer NOT NULL,
    ubicacion               integer,
    medidor_id_medidor      integer,
    num_casa                integer,
    num_ocupantes           integer,
    tipo_instalacion        varchar(255),
    dim_instalacion         varchar(255),
    actividad               varchar(255) NOT NULL,
    categoria               varchar(255) NOT NULL,
    fecha_registro          date NOT NULL,
    ruta_id_ruta            integer NOT NULL,
    codigo_fijo             integer NOT NULL,
    estado                  boolean NOT NULL DEFAULT true,
    correo                  varchar(150) NOT NULL,
    fecha_baja              date,
    motivo_baja             varchar(255),
    acepta_comunicaciones   boolean,
    fecha_consentimiento    timestamp,
    CONSTRAINT socio_pk PRIMARY KEY (id_socio),
    CONSTRAINT socio_codigo_fijo_uq UNIQUE (codigo_fijo),
    CONSTRAINT socio_persona_fk FOREIGN KEY (persona_id_persona) REFERENCES persona (id_persona),
    CONSTRAINT socio_rol_socio_fk FOREIGN KEY (rol_socio_id_rol_socio) REFERENCES rol_socio (id_rol_socio),
    CONSTRAINT socio_medidor_fk FOREIGN KEY (medidor_id_medidor) REFERENCES medidor (id_medidor),
    CONSTRAINT socio_ruta_fk FOREIGN KEY (ruta_id_ruta) REFERENCES ruta (id_ruta),
    CONSTRAINT socio_categoria_ck CHECK (categoria IN ('Social', 'Industrial', 'Comercial', 'Doméstico')),
    CONSTRAINT socio_codigo_fijo_ck CHECK (codigo_fijo > 0),
    CONSTRAINT socio_dim_instalacion_ck CHECK (dim_instalacion IN ('1 pulgada', '3/4 pulgada', '1/2 pulgada')),
    CONSTRAINT socio_num_ocupantes_ck CHECK (num_ocupantes >= 0 AND num_ocupantes <= 50),
    CONSTRAINT socio_tipo_instalacion_ck CHECK (tipo_instalacion IN ('Tubería negra', 'Polipropileno', 'CPVC', 'PVC')),
    CONSTRAINT socio_ubicacion_casa_ck CHECK (ubicacion >= 0 AND num_casa >= 0)
);

-- ---------- OPERACIONES ----------
CREATE TABLE estado (
    id_estado  integer GENERATED BY DEFAULT AS IDENTITY,
    estado     varchar(150) NOT NULL,
    CONSTRAINT estado_pk PRIMARY KEY (id_estado)
);

CREATE TABLE lectura (
    id_lectura                      integer GENERATED BY DEFAULT AS IDENTITY,
    fecha_lectura                   date NOT NULL,
    lectura_anterior                integer NOT NULL,
    lectura_actual                  integer NOT NULL,
    dias_lectura                    integer NOT NULL,
    observacion                     varchar(255),
    usuario_admin_id_usuario_admin  integer NOT NULL,
    medidor_id_medidor              integer NOT NULL,
    periodo_id_periodo              integer NOT NULL,
    consumo_m3                      numeric(30,2) NOT NULL,
    CONSTRAINT lectura_pk PRIMARY KEY (id_lectura),
    CONSTRAINT lectura_medidor_periodo_uq UNIQUE (medidor_id_medidor, periodo_id_periodo),
    CONSTRAINT lectura_usuario_admin_fk FOREIGN KEY (usuario_admin_id_usuario_admin)
        REFERENCES usuario_admin (id_usuario_admin),
    CONSTRAINT lectura_medidor_fk FOREIGN KEY (medidor_id_medidor) REFERENCES medidor (id_medidor),
    CONSTRAINT lectura_periodo_fk FOREIGN KEY (periodo_id_periodo) REFERENCES periodo (id_periodo),
    CONSTRAINT lectura_valores_ck CHECK (lectura_anterior >= 0
        AND lectura_actual >= lectura_anterior AND consumo_m3 >= 0)
);

CREATE TABLE aviso (
    id_aviso            integer GENERATED BY DEFAULT AS IDENTITY,
    fecha_emision       date NOT NULL,
    fecha_vencimiento   date NOT NULL,
    total_consumo       numeric(30,2) NOT NULL,
    total_aviso         numeric(30,2) NOT NULL,
    periodo_id_periodo  integer NOT NULL,
    estado_id_estado    integer NOT NULL,
    lectura_id_lectura  integer,
    socio_id_socio      integer NOT NULL,
    motivo_anulacion    varchar(255),
    fecha_anulacion     timestamp,
    CONSTRAINT aviso_pk PRIMARY KEY (id_aviso),
    CONSTRAINT aviso_periodo_fk FOREIGN KEY (periodo_id_periodo) REFERENCES periodo (id_periodo),
    CONSTRAINT aviso_estado_fk FOREIGN KEY (estado_id_estado) REFERENCES estado (id_estado),
    CONSTRAINT aviso_lectura_fk FOREIGN KEY (lectura_id_lectura) REFERENCES lectura (id_lectura),
    CONSTRAINT aviso_socio_fk FOREIGN KEY (socio_id_socio) REFERENCES socio (id_socio),
    CONSTRAINT aviso_anulacion_ck CHECK (estado_id_estado <> 5 OR motivo_anulacion IS NOT NULL)
);

-- ---------- COBRANZA ----------
CREATE TABLE metodo_pago (
    id_metodo_pago  integer GENERATED BY DEFAULT AS IDENTITY,
    metodo          varchar(150) NOT NULL,
    referencia      varchar(255),
    CONSTRAINT metodo_pago_pk PRIMARY KEY (id_metodo_pago)
);

CREATE TABLE pago (
    id_pago                     integer GENERATED BY DEFAULT AS IDENTITY,
    fecha_pago                  timestamp NOT NULL,
    monto_pagado                numeric(30,2) NOT NULL,
    cajero                      varchar(150) NOT NULL,
    aviso_id_aviso              integer,
    metodo_pago_id_metodo_pago  integer NOT NULL,
    vuelto                      numeric(30,2),
    caja_id_caja                integer,
    identificador_deuda         varchar(100),
    id_transaccion              varchar(100),
    forma_pago                  varchar(60),
    codigo_recaudacion          varchar(50),
    url_pasarela                varchar(500),
    qr_url                      varchar(500),
    estado_pago                 varchar(30) NOT NULL DEFAULT 'APROBADO',
    CONSTRAINT pago_pk PRIMARY KEY (id_pago),
    CONSTRAINT pago_aviso_fk FOREIGN KEY (aviso_id_aviso) REFERENCES aviso (id_aviso),
    CONSTRAINT pago_metodo_pago_fk FOREIGN KEY (metodo_pago_id_metodo_pago)
        REFERENCES metodo_pago (id_metodo_pago),
    CONSTRAINT pago_caja_fk FOREIGN KEY (caja_id_caja) REFERENCES caja (id_caja),
    CONSTRAINT pago_estado_ck CHECK (estado_pago IN ('PENDIENTE', 'APROBADO', 'EXPIRADO')),
    CONSTRAINT pago_montos_ck CHECK (monto_pagado >= 0 AND vuelto >= 0)
);

-- ---------- BITACORA (Administracion) ----------
CREATE TABLE bitacora (
    id_bitacora                     integer GENERATED BY DEFAULT AS IDENTITY,
    accion                          varchar(255) NOT NULL,
    fecha_hora                      timestamp NOT NULL,
    usuario_admin_id_usuario_admin  integer NOT NULL,
    CONSTRAINT bitacora_pk PRIMARY KEY (id_bitacora),
    CONSTRAINT bitacora_usuario_admin_fk FOREIGN KEY (usuario_admin_id_usuario_admin)
        REFERENCES usuario_admin (id_usuario_admin)
);

-- ---------- TIPOS DE CARGO (Configuracion) ----------
CREATE TABLE tipo_cargo (
    id_tipo      integer GENERATED BY DEFAULT AS IDENTITY,
    nombre       varchar(150) NOT NULL,
    descripcion  varchar(255),
    monto        numeric(30,2) NOT NULL,
    estado       boolean NOT NULL DEFAULT true,
    CONSTRAINT tipo_cargo_pk PRIMARY KEY (id_tipo),
    CONSTRAINT tipo_cargo_nombre_uq UNIQUE (nombre),
    CONSTRAINT tipo_cargo_monto_ck CHECK (monto >= 0)
);

-- ---------- CREDITO DE INSCRIPCION Y CUENTA DEL PORTAL (Atencion al Cliente) ----------
CREATE TABLE credito_inscripcion (
    id_credito          integer GENERATED BY DEFAULT AS IDENTITY,
    monto_pago          numeric(10,2) NOT NULL,
    estado              varchar(50) NOT NULL,
    num_cuota           integer NOT NULL,
    socio_id_socio      integer NOT NULL,
    periodo_id_periodo  integer NOT NULL,
    pago_id_pago        integer,
    CONSTRAINT credito_inscripcion_pk PRIMARY KEY (id_credito),
    CONSTRAINT credito_socio_cuota_uq UNIQUE (socio_id_socio, num_cuota),
    CONSTRAINT credito_socio_fk FOREIGN KEY (socio_id_socio) REFERENCES socio (id_socio),
    CONSTRAINT credito_periodo_fk FOREIGN KEY (periodo_id_periodo) REFERENCES periodo (id_periodo),
    CONSTRAINT credito_pago_fk FOREIGN KEY (pago_id_pago) REFERENCES pago (id_pago),
    CONSTRAINT credito_num_cuota_ck CHECK (num_cuota BETWEEN 1 AND 4),
    CONSTRAINT credito_monto_ck CHECK (monto_pago > 0),
    CONSTRAINT credito_estado_ck CHECK (estado IN ('PENDIENTE', 'PAGADA'))
);

CREATE TABLE cuenta_socio (
    id_cuenta_socio    integer GENERATED BY DEFAULT AS IDENTITY,
    usuario            varchar(150) NOT NULL,
    contraseña         varchar(500) NOT NULL,
    ultimo_acceso      timestamp,
    estado             boolean NOT NULL,
    socio_id_socio     integer NOT NULL,
    intentos_fallidos  integer NOT NULL DEFAULT 0,
    CONSTRAINT cuenta_socio_pk PRIMARY KEY (id_cuenta_socio),
    CONSTRAINT cuenta_socio_usuario_uq UNIQUE (usuario),
    CONSTRAINT cuenta_socio_socio_uq UNIQUE (socio_id_socio),
    CONSTRAINT cuenta_socio_socio_fk FOREIGN KEY (socio_id_socio) REFERENCES socio (id_socio)
);

-- ---------- CARGOS EXTRA (Operaciones) ----------
CREATE TABLE cargo_extra (
    id_cargo_extra      integer GENERATED BY DEFAULT AS IDENTITY,
    monto               numeric(30,2) NOT NULL,
    descripcion         varchar(150) NOT NULL,
    fecha_registro      date NOT NULL,
    estado              varchar(150) NOT NULL,
    tipo_cargo_id_tipo  integer NOT NULL,
    socio_id_socio      integer NOT NULL,
    periodo_id_periodo  integer NOT NULL,
    motivo_anulacion    varchar(255),
    fecha_anulacion     timestamp,
    pago_id_pago        integer,
    CONSTRAINT cargo_extra_pk PRIMARY KEY (id_cargo_extra),
    CONSTRAINT cargo_extra_tipo_fk FOREIGN KEY (tipo_cargo_id_tipo) REFERENCES tipo_cargo (id_tipo),
    CONSTRAINT cargo_extra_socio_fk FOREIGN KEY (socio_id_socio) REFERENCES socio (id_socio),
    CONSTRAINT cargo_extra_periodo_fk FOREIGN KEY (periodo_id_periodo) REFERENCES periodo (id_periodo),
    CONSTRAINT cargo_extra_pago_fk FOREIGN KEY (pago_id_pago) REFERENCES pago (id_pago),
    CONSTRAINT cargo_extra_monto_ck CHECK (monto > 0),
    CONSTRAINT cargo_extra_estado_ck CHECK (estado IN ('PENDIENTE', 'APLICADO', 'ANULADO')),
    CONSTRAINT cargo_extra_anulacion_ck CHECK (estado <> 'ANULADO' OR motivo_anulacion IS NOT NULL)
);

-- ---------- FACTURACION (simulada, no se envia al SIAT) ----------
CREATE TABLE factura (
    id_factura                      integer GENERATED BY DEFAULT AS IDENTITY,
    numero_factura                  integer NOT NULL,
    fecha_emision                   timestamp NOT NULL,
    nit_ci                          varchar(20) NOT NULL,
    razon_social                    varchar(255) NOT NULL,
    monto_total                     numeric(30,2) NOT NULL,
    cuf                             varchar(100) NOT NULL,
    codigo_control                  varchar(30) NOT NULL,
    leyenda                         varchar(500) NOT NULL,
    estado                          varchar(20) NOT NULL DEFAULT 'VIGENTE',
    pago_id_pago                    integer NOT NULL,
    usuario_admin_id_usuario_admin  integer,
    CONSTRAINT factura_pk PRIMARY KEY (id_factura),
    CONSTRAINT factura_numero_uq UNIQUE (numero_factura),
    CONSTRAINT factura_pago_uq UNIQUE (pago_id_pago),
    CONSTRAINT factura_pago_fk FOREIGN KEY (pago_id_pago) REFERENCES pago (id_pago),
    CONSTRAINT factura_usuario_admin_fk FOREIGN KEY (usuario_admin_id_usuario_admin)
        REFERENCES usuario_admin (id_usuario_admin),
    CONSTRAINT factura_monto_ck CHECK (monto_total >= 0),
    CONSTRAINT factura_estado_ck CHECK (estado IN ('VIGENTE', 'ANULADA'))
);

-- La bitacora es de solo lectura: no se puede modificar ni borrar (RNF-08)
CREATE OR REPLACE FUNCTION bitacora_solo_lectura() RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION 'La bitácora no se puede modificar ni eliminar';
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE TRIGGER bitacora_solo_lectura_tg
BEFORE UPDATE OR DELETE ON bitacora
FOR EACH ROW EXECUTE FUNCTION bitacora_solo_lectura();

